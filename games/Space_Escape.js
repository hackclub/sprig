setPushables({
  [ player ]: []
})

onInput("s", () => {
 //make plaer go down
  getFirst(player).y += 1
})
onInput("w", () => {
 //make plaer go up
  getFirst(player).y -= 1
})
onInput("d", () => {
 //make plaer go right
  getFirst(player).x += 1
})
onInput("a", () => {
 //make plaer go left
  getFirst(player).x -= 1
})


afterInput(() => {
  const p = getFirst(player);
  
  // Check everything on the same square as the player
  getTile(p.x, p.y).forEach(item => {
    
    // 1. If it's fuel: vanish it and unlock the door
    if (item.type === fuel) {
      item.remove(); 
      hasFuel = true;
      setSolids([player, wall]); 
    }
    
    // 2. If it's the pod: only let them win if they have fuel
    if (item.type === pod) {
      if (hasFuel) {
        addText("WIN!", { x: 6, y: 6, color: color`3` });
      } else {
        addText("NEED FUEL", { x: 5, y: 6, color: color`3` });
      }
    }
    
  });
});
  
    
