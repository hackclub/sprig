setPushables({
  [ player ]: []
})
let gameOver = false
onInput("w", () => {
  if (!gameOver) getFirst(player).y -= 1
})
onInput("a", () => {
  if (!gameOver) getFirst(player).x -= 1
})
onInput("d", () => {
  if (!gameOver) getFirst(player).x += 1
})
onInput("s", () => {
  if (!gameOver) getFirst(player).y += 1
})
onInput("j", () => {
  level = 0
  gameOver = false
  clearText()
  setMap(levels[level])
})
afterInput(() => {
  const p = getFirst(player)
  const asteroids = getAll(asteroid)
  const l = getFirst(planet)

  if (asteroids.some(a => p.x === a.x && p.y === a.y)) {
    gameOver = true
    playTune(losesound)
    addText("Press J to Restart", {
        x:2,
        y:10,
        color:3
    })   
    addText("Game Over!", {
      x: 6,
      y: 7,
      color: 3
    })
  }

  if (p.x === l.x && p.y === l.y) {
    level++

    if (level < levels.length) {
      setMap(levels[level])
      playTune(reachplanet)
    }
    if (level === levels.length) {
      gameOver = true
      playTune(winsound)
      addText("You Win", {
        x:7,
        y:7,
        color:3
      })
      addText("Press J to Restart", {
        x:2,
        y:10,
        color:3
      })
    }
  }
})
  

