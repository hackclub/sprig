setMap(maps.default);


function flashColor(colorName) {
  setMap(maps[colorName]);

  setTimeout(() => {
    setMap(maps.default);
  }, 300);
}

const colors = ["green", "yellow", "blue", "red"];

let sequence = [];
let position = 0;
let phase = "waiting";
let score = 0;

function updateStats() {
  clearText();



  addText(`SCORE ${score}`, {
    x: 6,
    y: 14,
    color: color`1`
  });
}

function startRound() {
  phase = "showing";
  position = 0;
  

  const randomIndex = Math.floor(Math.random() * colors.length);
  const nextColor = colors[randomIndex];

  sequence.push(nextColor);
  playTune(click)
  updateStats();

  setTimeout(() => {
    showSequence(0);
  }, 600);
}

function showSequence(index) {
  if (index >= sequence.length) {
    phase = "input";
    playTune(beep2)
    return;
  }

  flashColor(sequence[index]);
//beep when color appears
  playTune(beep)

  setTimeout(() => {
    showSequence(index + 1);
  }, 650);
}

function checkInput(colorName) {
  if (phase !== "input") {
    return;
  }

  const expectedColor = sequence[position];

  if (colorName !== expectedColor) {
    phase = "over";
    setMap(maps.blank);
    clearText();

    addText("Game Over!", { y: 4 });
    addText(`Score: ${score}`, { y: 6 });
    playTune(loose)

    return;
  }

  phase = "feedback";
  flashColor(colorName);
  position += 1;

  if (position === sequence.length) {
    score += 1;

    setTimeout(() => {
      startRound();
    }, 800);
  } else {
    setTimeout(() => {
      phase = "input";
    }, 350);
  }
}

onInput("w", () => checkInput("green"));
onInput("a", () => checkInput("yellow"));
onInput("s", () => checkInput("blue"));
onInput("d", () => checkInput("red"));

startRound();