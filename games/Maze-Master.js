// 3. Build the maze map
setMap(map`
  wwwwwww
  wp..w.w
  www.w.w
  w...w.w
  w.www.w
  w....gw
  wwwwwww`);

// 4. Make walls solid
setSolids([player, wall]);

// 5. Move with W, A, S, D keys
onInput("w", () => { getFirst(player).y -= 1; });
onInput("s", () => { getFirst(player).y += 1; });
onInput("a", () => { getFirst(player).x -= 1; });
onInput("d", () => { getFirst(player).x += 1; });

// 6. Win when touching the goal
afterInput(() => {
  if (tilesWith(player, goal).length > 0) {
    addText("YOU WIN!", { x: 6, y: 7, color: color`7` });
  }
});
