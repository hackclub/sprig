function move(cube, m) {
  let newCube = [[], [], [], [], [], []];
  let aidx = 0;
  for (let i = 0; i < 6; i++) {
    for (let j = 0; j < 9; j++) {
      newCube[i][j] = cube[moves[m][aidx][0]][moves[m][aidx][1]]
      aidx+=1;
    }
  }
  return newCube;
}

