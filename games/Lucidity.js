const playerstart = { x: getFirst(player).x, y: getFirst(player).y };
const shadowstart = { x: getFirst(shadow).x, y: getFirst(shadow).y };
const blockstart = { x: getFirst(block).x, y: getFirst(block).y };

setPushables({
  [player]: [block, player, orb, ]
})

function move(dx, dy) {
  const p = getFirst(player);
  const s = getFirst(shadow);
  const b = getFirst(block);
  const h = getFirst(place); // house/goal

  p.x += dx;
  p.y += dy;
  s.x += dx;
  s.y += dy;

  const dxDiff = p.x - s.x;
  const dyDiff = p.y - s.y;
  if (dxDiff * dxDiff + dyDiff * dyDiff <= 2) {
    p.x = playerstart.x;
    p.y = playerstart.y;
    s.x = shadowstart.x;
    s.y = shadowstart.y;
    b.x = blockstart.x;
    b.y = blockstart.y;
    clearText()
    addText("Caught!", { x: 6, y: 4, color: color`3` });
    setTimeout(() => {
      clearText();
    }, 1000);
    playTune(gameover)

  }

  if (b.x === h.x && b.y === h.y) {
    level += 1; // go to next level

    if (level < levels.length) {
      setMap(levels[level]);

      // Update start positions for the new level
      playerstart.x = getFirst(player).x;
      playerstart.y = getFirst(player).y;
      shadowstart.x = getFirst(shadow).x;
      shadowstart.y = getFirst(shadow).y;
      blockstart.x = getFirst(block).x;
      blockstart.y = getFirst(block).y;

      addText("Level " + (level + 1) + "!", { x: 5, y: 4, color: color`3` });

      setTimeout(() => {
        clearText();
      }, 1000);
    } else {
      addText("You Win!", { x: 5, y: 4, color: color`2` });
    }
  }
}

