const levels_wolf = [0, 0, [[1, 3]], [[3, 1], [5, 5]], [[2, 2], [2, 5], [4, 1], [4, 4], [6, 1], [6, 4], [8, 1], [8, 3]]]

setBackground(bg)

setSolids([player, fence])

let playing = true;
let win = false;
let wolf = 0;
let last_position = [0, 0];

function player_position() {
  return [getFirst(player).x, getFirst(player).y]
}

function load_level(l) {
  clearText();
  setMap(levels[l]);
  playing = true;
  if (levels_wolf[l]) {
    for (const item of levels_wolf[l]) {
      addSprite(item[0], item[1], enemy);
    }
  }
  last_position = player_position();
}

onInput("w", () => {
  if (playing) {
    getFirst(player).y -= 1;
  }
})
onInput("s", () => {
  if (playing) {
    getFirst(player).y += 1;
  }
})
onInput("a", () => {
  if (playing) {
	getFirst(player).x -= 1;
  }
})
onInput("d", () => {
  if (playing) {
	getFirst(player).x += 1;
  }
})
onInput("j", () => {
  if (!win) {
    load_level(level);
  }
})
onInput("k", () => {
  //level += 1
  //load_level(level);
})

load_level(level);

afterInput(() => {
  const this_position = player_position();
  if (last_position[0] === this_position[0] && last_position[1] === this_position[1]) {
    console.log("no move");
    return
  }
  last_position = this_position;

  
  const eaten_count_before_update = tilesWith(player, enemy);
  if (eaten_count_before_update.length) {
    playing = false;
    addText("You Walked Into Wolf", {y:1, color: color`2`});
    addText("And Have Been Eaten", {y:2, color: color`2`});
    addText("By Wolf", {y:3, color: color`2`});
    addText("Press J To Restart", {y:14, color: color`2`});
    return
  }

  
  for (const item of getAll(enemy)) {
    const tile = getTile(item.x, item.y).at(-1).type
    switch (tile) {
      case "5": case "0": item.x += 1; break; // right
      case "7": case "1": item.x -= 1; break; // left
      case "6": case "2": item.y += 1; break; // down
      case "4": case "3": item.y -= 1; break; // up
    }
  }
  
  const eaten_count_after_update = tilesWith(player, enemy);
  if (eaten_count_after_update.length) {
    playing = false;
    addText("Wolf Walked Into You", {y:1, color: color`2`});
    addText("And You Are Eaten", {y:2, color: color`2`});
    addText("By Wolf", {y:3, color: color`2`});
    addText("Press J To Restart", {y:14, color: color`2`});
    
  } else {
    const win_count = tilesWith(player, goal);
    if (win_count.length) {
      level = level + 1;
      
      if (level < levels.length) {
        load_level(level);
        
      } else {
        addText("You Win!", {y:1, color: color`2`});
        addText("Thanks For Playing!", {y:14, color: color`2`});
        playing = false;
        win = true;
      }
    }
  }
});