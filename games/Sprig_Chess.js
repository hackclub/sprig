// Song handling

function shuffleSongs() {
  songQueue = [];
  for (let i = 0; i < songs.length; i++) {
    songQueue.push(i);
  }

  for (let i = songQueue.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    const temp = songQueue[i];
    songQueue[i] = songQueue[j];
    songQueue[j] = temp;
  }
}

function stopMusic() {
  musicEnabled = false;

  if (songTimer != null) {
    clearTimeout(songTimer);
    songTimer = null;
  }

  if (titleTimer != null) {
    clearTimeout(titleTimer);
    titleTimer = null;
  }

  playbacks.forEach((playback) => playback.end());
  playbacks = [];
}

function playSong(songIndex) {
  stopMusic();

  currentSong = songIndex;
  song = songs[currentSong];
  musicEnabled = true;

  setSongTitle(song.name);
  playbacks.push(playTune(song.tune));

  songTimer = setTimeout(() => {
    if (musicEnabled) playNextSong();
  }, song.duration + 250);
}

function playNextSong() {
  if (songQueue.length === 0) shuffleSongs();
  playSong(songQueue.shift());
}

