const MoveY = (dy) => { getFirst(player).y += dy}
const MoveX = (dx) => { getFirst(player).x += dx}

onInput("s", () => {MoveY(1)})
onInput("d", () => {MoveX(1)})
onInput("w", () => {MoveY(-1)})
onInput("a", () => {MoveX(-1)})


let playback
let won = false
afterInput(() => {
  const targetNumber = tilesWith(cowbackup).length

  let p = getFirst(player)
  let c = getFirst(cowbackup)

  let dist = Math.abs(p.x - c.x) + Math.abs(p.y - c.y)

  if (dist <= 5 && won == false) {
    if (!playback) {
      playback = playTune(moo, Infinity)
    }
  } else {
    if (playback) {
      playback.end()
      playback = null
    }
  }
  
  
  // count the number of tiles with goals and boxes
  const numberCovered = tilesWith(cowbackup, player).length;

  // if the number of goals is the same as the number of goals covered
  // all goals are covered and we can go to the next level
  if (numberCovered === targetNumber) {
    // increase the current level number
    level = level + 1;

    const currentLevel = levels[level];

    // make sure the level exists and if so set the map
    // otherwise, we have finished the last level, there is no level
    // after the last level
    if (currentLevel !== undefined) {
      setMap(currentLevel);
    } else {
      won = true
      addText("You found all the cows!!", { y: 4, color: color`3` });
    }
  }
});
