let n = 0
let dead = false

onInput("w", () => { if (!dead) getFirst(p).y -= 1 })
onInput("s", () => { if (!dead) getFirst(p).y += 1 })
onInput("a", () => { if (!dead) getFirst(p).x -= 1 })
onInput("d", () => { if (!dead) getFirst(p).x += 1 })

afterInput(() => {
  if (dead) return
  let me = getFirst(p)

  // orbs
  if (tilesWith(p, o).length > 0) {
    n++
    clearTile(me.x, me.y)
    addSprite(me.x, me.y, p)
  }

  // spirits
  if (tilesWith(p, s).length > 0) {
    dead = true
    addText("GAME OVER", { x: 5, y: 7, color: color`3` })
  }

  // win
  if (tilesWith(p, d).length > 0 && n == 3) {
    dead = true
    addText("YOU WIN!", { x: 6, y: 7, color: color`4` })
  }
})
