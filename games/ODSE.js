// ---------- main loop (10 ticks per second) ----------
function tick() {
  if (state === "between") {
    betweenTicks--
    if (betweenTicks <= 0) loadStage(stageN + 1)
    return
  }
  if (state === "intro") {
    introTicks--
    if (introTicks <= 0) beginStage()
    return
  }
  if (state !== "play") return
  tickN++
  if (bannerTicks > 0) {
    bannerTicks--
    if (bannerTicks === 0 || bannerTicks * 2 === bannerTotal) drawHud()
  }
  if (invuln > 0) invuln--
  if (spearCd > 0) spearCd--
  if (stepAnim > 0) stepAnim--
  if (dashCd > 0) dashCd--

  // gravity & jumping
  let fell = false
  if (jumpTicks > 0 && !blocks(pl.x, pl.y - 1)) {
    pl.y -= 1
    jumpTicks--
  } else {
    jumpTicks = 0
    if (!blocks(pl.x, pl.y + 1)) { pl.y += 1; fell = true }
  }
  // airborne drift: keep moving forward (1 tile every other tick) until you land
  if (drift) {
    if (jumpTicks > 0 || !blocks(pl.x, pl.y + 1)) {
      if (tickN % 2 === 0 && !blocks(pl.x + drift, pl.y)) pl.x += drift
    } else drift = 0
  }

  updateSpears();  if (state !== "play") return
  updateEnemies(); if (state !== "play") return
  animateEnemies()
  if (boss) { boss.update(); if (state !== "play") return }
  updateProjs();   if (state !== "play") return
  updateBolts()
  checkPlayer(fell); if (state !== "play") return
  setPlayerType()
}

