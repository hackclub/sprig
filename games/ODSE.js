// NOTE: assigning sprite.type deletes the sprite and makes a NEW one, so we never
// keep a reference across a type change (see swapPlayer).
function sgn(v) { return v > 0 ? 1 : v < 0 ? -1 : 0 }
function oob(x, y) { return x < 0 || y < 0 || x >= W || y >= H }
function solid(x, y) {
  if (oob(x, y)) return true
  return getTile(x, y).some(s => s.type === "w" || s.type === "x" || s.type === "#")
}
function blocks(x, y) {
  if (oob(x, y)) return true
  return getTile(x, y).some(s => s.type === "w" || s.type === "x" || s.type === "#" || bossSolid.includes(s.type))
}
function lastOf(x, y, type) {
  const l = getTile(x, y).filter(s => s.type === type)
  return l[l.length - 1]
}
function clearWarn() { getAll("!").forEach(s => s.remove()) }
function warnAt(x, y) { if (!oob(x, y)) addSprite(x, y, "!") }
function enemyOf(sprite) { return enemies.find(e => e.s === sprite) }
function clearLine(x1, x2, y) {
  const a = Math.min(x1, x2), b = Math.max(x1, x2)
  for (let x = a + 1; x < b; x++) if (blocks(x, y)) return false
  return true
}
function remaining() {
  if (st.need === "coins") return getAll("d").length
  if (st.need === "targets") return getAll("K").length
  return 0
}

function swapPlayer(t) {
  if (pl.type === t) return
  const x = pl.x, y = pl.y
  pl.remove()
  addSprite(x, y, t)
  pl = lastOf(x, y, t)
}
// two-frame walk cycle: stride (p/P) and legs-together (1/2). The frame flips with the
// tile you stand on while walking, and legs-together is used in the air.
function setPlayerType() {
  const blink = invuln > 0 && tickN % 2 === 0
  const air = !blocks(pl.x, pl.y + 1)
  const b = air || (stepAnim > 0 && pl.x % 2 === 0)
  const R = blink ? "v" : (b ? "1" : "p"), L = blink ? "V" : (b ? "2" : "P")
  swapPlayer(facing > 0 ? R : L)
}

// enemies flip between two frames every other tick (type swap -> re-acquire the sprite)
const ALT = { n: "4", h: "5", b: "6", G: "7", s: "8", t: "9", R: "$" }
function animateEnemies() {
  for (let i = 0; i < enemies.length; i++) {
    const e = enemies[i], alt = ALT[e.kind]
    if (!alt) continue
    const want = (((tickN + i) >> 1) % 2) ? alt : e.kind
    if (e.s.type === want) continue
    const x = e.s.x, y = e.s.y
    e.s.type = want
    e.s = lastOf(x, y, want)
  }
}

