// Left/right are single grid steps. Double-tap a direction to DASH up to 3 tiles (also
// mid-air) to clear gaps. A jump started right after a step keeps drifting forward.
function moveH(dir) {
  if (state !== "play") return
  const now = Date.now()
  const dbl = dir === lastDir && now - lastKeyT >= 90 && now - lastKeyT <= 330
  lastDir = dir; lastKeyT = now
  facing = dir
  if (drift && drift !== dir) drift = 0
  if (dbl && dashCd <= 0) {
    let n = 0
    while (n < 3 && !blocks(pl.x + dir, pl.y)) { pl.x += dir; n++ }
    if (n > 0) { dashCd = 8; stepAnim = 3; if (invuln < 3) invuln = 3 }
  } else {
    const nx = pl.x + dir
    if (!blocks(nx, pl.y)) { pl.x = nx; stepAnim = 3 }
  }
  setPlayerType()
  checkPlayer(false)
}
