  ["f", "bgSky"], ["g", "bgCave"], ["j", "bgDusk"], ["y", "bgStorm"], ["m", "bgHall"],
  ["k", "bgUnder"], ["l", "bgSunset"], ["i", "bgNight"], ["c", "bgGrove"]
