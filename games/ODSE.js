// each stage swaps in its own boss sprites (cast) on top of the base legend
function legendFor(cast) {
  const out = BASE.map(([k, n]) => [k, ART[cast[k] || n]])
  Object.keys(cast).forEach(k => {
    if (!BASE.some(b => b[0] === k)) out.push([k, ART[cast[k]]])
  })
  return out
}

