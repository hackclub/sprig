function blinkyMove() {
  var oldX = getFirst(blinky).x
  var oldY = getFirst(blinky).y
  var newX = oldX
  var newY = oldY
  var pacmanX = getFirst(pacman).x
  var pacmanY = getFirst(pacman).y
  var trappedCount = 0
  while (oldX == newX && oldY == newY) {
    if (trappedCount == 16) {
      var randomInt = Math.floor(Math.random()*4)
      if (randomInt == 0) { // Right
        checkOverlap("ghost", (getFirst(blinky).x + 1), newY)
        getFirst(blinky).x += 1
        newX = getFirst(blinky).x
      }
      else if (randomInt == 1) { // Down
        checkOverlap("ghost", newX, (getFirst(blinky).y + 1))
        getFirst(blinky).y += 1
        newY = getFirst(blinky).y
      }
      else if (randomInt == 2) { // Left
        checkOverlap("ghost", (getFirst(blinky).x - 1), newY)
        getFirst(blinky).x -= 1
        newX = getFirst(blinky).x
      }
      else if (randomInt == 3) { // Up
        checkOverlap("ghost", newX, (getFirst(blinky).y - 1))
        getFirst(blinky).y -= 1
        newY = getFirst(blinky).y
      }
        break
    }
    else if (pacmanX > oldX) { // Right
      checkOverlap("ghost", (getFirst(blinky).x + 1), newY)
      getFirst(blinky).x += 1
      newX = getFirst(blinky).x
      trappedCount++
    }
    else if (pacmanY > oldY) { // Down
      checkOverlap("ghost", newX, (getFirst(blinky).y + 1))
      getFirst(blinky).y += 1
      newY = getFirst(blinky).y
      trappedCount++
    }
    else if (pacmanX < oldX) { // Left
      checkOverlap("ghost", (getFirst(blinky).x - 1), newY)
      getFirst(blinky).x -= 1
      newX = getFirst(blinky).x
      trappedCount++
      }
    else if (pacmanY < oldY) { // Up
      checkOverlap("ghost", newX, (getFirst(blinky).y - 1))
      getFirst(blinky).y -= 1
      newY = getFirst(blinky).y
      trappedCount++
    }
  }
}

function ghostMove() {
  for (let i = 1; i < 4; i++) {
    var oldX = getFirst(ghosts[i]).x
    var oldY = getFirst(ghosts[i]).y
    var newX = oldX
    var newY = oldY
    var trappedCount = 0
    while (oldX == newX && oldY == newY) {
      var randomInt = Math.floor(Math.random()*4)
      if (trappedCount == 16) {
        break
      }
      else if (randomInt == 0) {
        checkOverlap("ghost", (getFirst(ghosts[i]).x + 1), newY)
        getFirst(ghosts[i]).x += 1
        newX = getFirst(ghosts[i]).x
        trappedCount++
      }
      else if (randomInt == 1) {
        checkOverlap("ghost", newX, (getFirst(ghosts[i]).y + 1))
        getFirst(ghosts[i]).y += 1
        newY = getFirst(ghosts[i]).y
        trappedCount++
      }
      else if (randomInt == 2) {
        checkOverlap("ghost", (getFirst(ghosts[i]).x - 1), newY)
        getFirst(ghosts[i]).x -= 1
        newX = getFirst(ghosts[i]).x
        trappedCount++
      }
      else if (randomInt == 3) {
        checkOverlap("ghost", newX, (getFirst(ghosts[i]).y - 1))
        getFirst(ghosts[i]).y -= 1
        newY = getFirst(ghosts[i]).y
        trappedCount++
      }
    }
  }
}

function update() {
  var pacmanX = getFirst(pacman).x
  var pacmanY = getFirst(pacman).y
  if (getTile(pacmanX, pacmanY).length == 2) {
    for (let i = 0; i < getAll(dot).length; i++) {
      if (pacmanX == getAll(dot)[i].x && pacmanY == getAll(dot)[i].y) {
        getAll(dot)[i].remove()
        score += 100;
      }
    }
  }
  addText("SCORE: " + score.toString(), {
      x: 0,
      y: 0,
      color: color`2`
  })
  if (score == 13200) {
    for (let i = 0; i < 17; i++) {
      for (let j = 0; j < 14; j++) {
        clearTile(i, j)
      }
    }
    clearText()
    addText("LEVEL CLEARED", {
      x: 4,
      y: 9,
      color: color`2`
    })
    addText("SCORE: " + score.toString(), {
      x: 4,
      y: 11,
      color: color`2`
    })
  }
}

function checkOverlap(kind, newX, newY) {
  if (kind == "pacman") {
  for (let i = 0; i < 4; i++) {
    var pacmanX = newX
    var pacmanY = newY
    var ghostX = getFirst(ghosts[i]).x
    var ghostY = getFirst(ghosts[i]).y
      if (pacmanX == ghostX && pacmanY == ghostY) {
        for (let i = 0; i < 17; i++) {
          for (let j = 0; j < 14; j++) {
            clearTile(i, j)
          }
        }
        clearText()
        addText("GAME OVER", {
          x: 5,
          y: 9,
          color: color`2`
        })
        addText("SCORE: " + score.toString(), {
          x: 5,
          y: 11,
          color: color`2`
        })
        clearInterval(function(){blinkyMove()})
        clearInterval(function(){ghostMove()})
        
      }
    }
  } // End if statement
  if (kind == "ghost") {
    for (let i = 0; i < 4; i++) {
    var pacmanX = getFirst(pacman).x
    var pacmanY = getFirst(pacman).y
    var ghostX = newX
    var ghostY = newY
      if (pacmanX == ghostX && pacmanY == ghostY) {
        for (let i = 0; i < 17; i++) {
          for (let j = 0; j < 14; j++) {
            clearTile(i, j)
          }
        }
        clearText()
        addText("GAME OVER", {
          x: 5,
          y: 9,
          color: color`2`
        })
        addText("SCORE: " + score.toString(), {
          x: 5,
          y: 11,
          color: color`2`
        })
      }
    }
  } // End if statement
}

