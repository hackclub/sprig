function startStage() {
  clearText()
  setMap(stages[stage])
  addText("Stage " + (stage + 1) + "/5", { y: 0, color: color`7` })
}

startStage()
setSolids([ player, wall ])

onInput("w", () => { getFirst(player).y -= 1 })
onInput("s", () => { getFirst(player).y += 1 })
onInput("a", () => { getFirst(player).x -= 1 })
onInput("d", () => { getFirst(player).x += 1 })

afterInput(() => {
  if (tilesWith(player, gem).length > 0) {
    getFirst(gem).remove()
  }

  if (tilesWith(player, spike).length > 0) {
    startStage()
  }

  if (tilesWith(player, portal).length > 0) {
    if (getAll(gem).length > 0) {
      addText("Collect all gems!", { y: 14, color: color`3` })
    } else {
      stage += 1
      if (stage < stages.length) {
        startStage()
      } else {
        clearText()
        addText("YOU WIN!", { y: 7, color: color`7` })
      }
    }
  }
})
