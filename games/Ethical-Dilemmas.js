function startGame() {
  currentState = STATES.MENU;
  
  currentQuestionIndex = 0;
  selectedAnswer = 0;

  love_self = 0;
  love_others = 0;
  hate_all = 0;
  
  animationButtonYesIsPressed = false;
  animationButtonNoIsPressed = false;

  showDialogue("Press left to start!")
  
  setMap(map`
abcde
f...j
f...m
npppr`);
  addSprite(1, 3, yes_button);
  addSprite(3, 3, no_button);

  applyMuteSetting();
  
  addSprite(2, 3, center_center_bottom);
  addSprite(1, 2, controller_icon_yes);
  addSprite(1, 3, controller_icon_yes_bottom);
  addSprite(3, 2, controller_icon_no);
  addSprite(3, 3, controller_icon_no_bottom);
}

function showDialogue(text) {
  clearText();
  const words = text.split(" ");
  const lines = Array(7).fill("");
  let lineIndex = 0;
  for (const word of words) {
    if (word === "<n>" || lines[lineIndex].length + word.length > 15) {
      lineIndex++;
    }
    if (word !== "<n>") {
      lines[lineIndex] += (lines[lineIndex] ? " " : "") + word;
    }
  }
  for (let i = 0; i < 7; i++) {
    if (lines[i]) {
      addText(lines[i], { x: 1, y: 3 + i, color: color`0` });
    }
  }
}

function tryPressButton(num, onDone) {
  if (animationButtonNoIsPressed === true || animationButtonYesIsPressed === true) {return false;}
  if (num === 0) {
    buttonAnimate(num, getFirst(no_button), onDone);
    return true;
  }
  if (num === 1) {
    buttonAnimate(num, getFirst(yes_button), onDone);
    return true;
  }
}

const sfx_button_up = tune`
73.89162561576354,
73.89162561576354: C5~73.89162561576354 + C4~73.89162561576354,
2216.7487684729062`
const sfx_button_down = tune`
73.89162561576354,
73.89162561576354: C4~73.89162561576354 + F5~73.89162561576354,
2216.7487684729062`
function buttonAnimate(num, btn, onDone) {
  if (!speakerMuted) { playTune(sfx_button_down); }
  if (num === 0) {
    animationButtonNoIsPressed = true;
    btn.type = no_button_pressed;
    setTimeout(() => {
      btn.type = no_button;
      animationButtonNoIsPressed = false;
      if (!speakerMuted) { playTune(sfx_button_up); }
    onDone();
    }, 800);
  }
  if (num === 1) {
    animationButtonYesIsPressed = true;
    btn.type = yes_button_pressed;
    setTimeout(() => {
      btn.type = yes_button;
      animationButtonYesIsPressed = false;
      if (!speakerMuted) { playTune(sfx_button_up); }
    onDone();
    }, 800);
  }
}

function applyMuteSetting() {
  if (!getFirst(speaker_icon) && !getFirst(speaker_icon_muted)) { // First time
    addSprite(4, 1, speaker_icon);
  }
  if (!getFirst(right_side_controller_up) && !getFirst(right_side_controller_down)) { // First time
    addSprite(4, 2, right_side_controller_down);
  }
  const sprite_speaker = getFirst(speaker_icon) || getFirst(speaker_icon_muted);
  const sprite_icon = getFirst(right_side_controller_up) || getFirst(right_side_controller_down);
  if (speakerMuted) {
    sprite_speaker.type = speaker_icon_muted;
    sprite_icon.type = right_side_controller_up;
  }
  else {
    sprite_speaker.type = speaker_icon;
    sprite_icon.type = right_side_controller_down;
  }
}

function keyMute(num) {
  if (currentState !== STATES.FINISHED) {
    if (speakerMuted == num) {
      speakerMuted = !speakerMuted // Swtich mute state
      applyMuteSetting();
    }
  }
}

function keyYes() {
  tryPressButton(1, () => {
  if (currentState === STATES.MENU) {
    stateToQuestions();
  } 
  else if (currentState === STATES.QUESTION) {
    answerQuestion(1);
  }
  else if (currentState === STATES.FINISHED) {
    startGame();
  }
  });
}

function keyNo() {
  if (currentState !== STATES.FINISHED) {
    tryPressButton(0, () => {
      if (currentState === STATES.QUESTION) {
        answerQuestion(0);
      }
      // "No" shouldnt work at start 
    });
  }
}

function stateToQuestions() {
  currentState = STATES.QUESTION;
  addSprite(2, 3, questionmark)

  nextQuestion(); // First question
}

function addTrait(q) {
  if (q === "love_self") { 
    love_self++ 
  }
  else if (q === "love_others") {
    love_others++ 
  }
}

function answerQuestion(num) {
  const q = questions[currentQuestionIndex];
  if (num === 0) {
    addTrait(q.no);
  }
  else if (num === 1) {
    addTrait(q.yes);
  }
  if (currentQuestionIndex === questions.length - 1) { displayFinished() }
  else {
    currentQuestionIndex++
    nextQuestion();
  }
}

function nextQuestion() {
  const q = questions[currentQuestionIndex];
  showDialogue(q.question)

}

function getBarSprites(num, isSelf) {
  const bar_sprites = [];
  const steps = Math.round(num * 10); // 10 is halfsteps over 5 tiles
  
  for (let i = 0; i < 5; i++) { // 5 steps
    if (steps >= (i + 1) * 2) {
      bar_sprites.push({
        x: i,
        sprite: isSelf ? love_self_full : love_others_full
      });
    }
    else if (steps >= i * 2 + 1) {
      bar_sprites.push({
        x: i,
        sprite: isSelf ? love_self_half : love_others_half
      });
    }
  }
  return bar_sprites;
}

function drawBar(num, startY, isSelf) {

  for (const { x, sprite } of getBarSprites(num, isSelf)) {
    addSprite(x, startY, sprite);
  }
}

function displayFinished() {
  clearText();
  currentState = STATES.FINISHED;
  
  percent_love_self = love_self / questions.length;
  percent_love_others = love_others / questions.length;
  
  setMap(map`
ABCDe
EF..j
JK..m
npppr`);
  
  addSprite(1, 3, yes_button);
  addSprite(1, 2, controller_icon_yes);
  addSprite(1, 3, controller_icon_yes_bottom);
  
  drawBar(percent_love_self, 1, true);
  drawBar(percent_love_others, 2, false);
  
  addSprite(2, 3, restart);
}

